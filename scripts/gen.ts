#!/usr/bin/env bun
// Generated pages (D24). Each source in sync/registry.yaml may declare
//   generated:
//     - page: trunks/reference/cli      # page path without .mdx
//       generator: markdown              # markdown | keep-a-changelog
//       from: docs/guide/reference/cli.md
//       title: CLI reference
//       sidebarTitle: CLI                # optional
//       description: ...
// The source file is read at the source's lastSynced commit: the local checkout
// when present, otherwise the GitHub API (CI; GITHUB_TOKEN is used when set).
//
//   bun scripts/gen.ts [--project <slug>]           write the pages
//   bun scripts/gen.ts [--project <slug>] --check   exit 1 when a page differs

import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

type Generated = { page: string; generator: string; from: string; title: string; sidebarTitle?: string; description: string };
type Source = { name: string; lastSynced: string; generated?: Generated[] };
type Project = { slug: string; repo: string; checkout: string; sources: Source[] };

const root = join(dirname(new URL(import.meta.url).pathname), "..");
const registry = Bun.YAML.parse(readFileSync(join(root, "sync/registry.yaml"), "utf8")) as { projects: Project[] };
const args = process.argv.slice(2);
const check = args.includes("--check");
const only = args.includes("--project") ? args[args.indexOf("--project") + 1] : undefined;

async function readSource(project: Project, sha: string, path: string): Promise<string> {
  const checkout = resolve(root, project.checkout);
  if (existsSync(checkout)) {
    const proc = Bun.spawnSync(["git", "-C", checkout, "show", `${sha}:${path}`], { stdout: "pipe", stderr: "pipe" });
    if (proc.exitCode === 0) return proc.stdout.toString();
  }
  const headers: Record<string, string> = { Accept: "application/vnd.github.raw", "User-Agent": "websublime-docs" };
  if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  const res = await fetch(`https://api.github.com/repos/${project.repo}/contents/${path}?ref=${sha}`, { headers });
  if (!res.ok) throw new Error(`${project.slug}: cannot read ${path} at ${sha} (${res.status})`);
  return res.text();
}

// Makes plain Markdown safe for MDX: HTML comments (maintainer notes) are
// dropped, and outside code `{`, `}` and `<` (before a letter or `/`) are escaped.
function toMdx(markdown: string): string {
  let fenced = false;
  return markdown
    .replace(/<!--[\s\S]*?-->\n?/g, "")
    .split("\n")
    .map((line) => {
      if (/^\s*(```|~~~)/.test(line)) fenced = !fenced;
      if (fenced || /^\s*(```|~~~)/.test(line)) return line;
      return line
        .split(/(`[^`]*`)/)
        .map((part, i) => (i % 2 ? part : part.replace(/[{}]/g, (c) => `\\${c}`).replace(/<(?=[A-Za-z/])/g, "&lt;")))
        .join("");
    })
    .join("\n");
}

function frontmatter(entry: Generated, project: Project, from: string, sha: string): string {
  const lines = ["---", `title: ${JSON.stringify(entry.title)}`];
  if (entry.sidebarTitle) lines.push(`sidebarTitle: ${JSON.stringify(entry.sidebarTitle)}`);
  lines.push(`description: ${JSON.stringify(entry.description)}`, "---", "");
  lines.push(`{/* Generated by scripts/gen.ts (${entry.generator}) from ${project.repo}:${from} at ${sha.slice(0, 12)}. Do not edit by hand; regenerate with scripts/gen.ts. */}`, "", "");
  return lines.join("\n");
}

const generators: Record<string, (text: string) => string> = {
  // A Markdown document; its first H1 is dropped (the page title replaces it).
  markdown: (text) => toMdx(text.replace(/^# .*\n+/m, "")),
  // Keep a Changelog: one <Update> per released version; [Unreleased] and the
  // preamble are left out (D5), as are trailing link references.
  "keep-a-changelog": (text) => {
    const body = text.replace(/^\[[^\]]+\]:\s+\S+\s*$/gm, "");
    const sections = body.split(/^## /m).slice(1);
    return sections
      .map((section) => {
        const [heading, ...rest] = section.split("\n");
        const m = /^\[?([^\]\s]+)\]?(?:\s*-\s*(\S+))?/.exec(heading);
        if (!m || /unreleased/i.test(m[1])) return "";
        const content = toMdx(rest.join("\n").trim()).replace(/^### /gm, "## ");
        return `<Update label="${m[1]}"${m[2] ? ` description="${m[2]}"` : ""}>\n\n${content}\n\n</Update>\n`;
      })
      .filter(Boolean)
      .join("\n");
  },
};

let stale = 0;
for (const project of registry.projects.filter((p) => !only || p.slug === only)) {
  for (const source of project.sources) {
    for (const entry of source.generated ?? []) {
      const generate = generators[entry.generator];
      if (!generate) throw new Error(`${project.slug}/${source.name}: unknown generator ${entry.generator}`);
      const text = await readSource(project, source.lastSynced, entry.from);
      const output = `${frontmatter(entry, project, entry.from, source.lastSynced)}${generate(text).trim()}\n`;
      const path = join(root, `${entry.page}.mdx`);
      const current = existsSync(path) ? readFileSync(path, "utf8") : null;
      if (current === output) continue;
      if (check) {
        console.error(`out of date: ${entry.page}.mdx (run: bun scripts/gen.ts --project ${project.slug})`);
        stale++;
      } else {
        mkdirSync(dirname(path), { recursive: true });
        writeFileSync(path, output);
        console.log(`wrote ${entry.page}.mdx`);
      }
    }
  }
}
if (stale) process.exit(1);
if (check) console.log("generated pages are up to date");
