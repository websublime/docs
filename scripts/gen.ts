#!/usr/bin/env bun
// Generated pages (D24). Each source in sync/registry.yaml may declare
//   generated:
//     - page: trunks/reference/cli      # page path without .mdx
//       generator: markdown              # markdown | keep-a-changelog
//       from: docs/guide/reference/cli.md
//       title: CLI reference
//       sidebarTitle: CLI                # optional
//       description: ...
// The source file is read at the source's lastSynced commit: the local checkout
// when present, otherwise the GitHub API (CI; GITHUB_TOKEN is used when set).
//
//   bun scripts/gen.ts [--project <slug>]           write the pages
//   bun scripts/gen.ts [--project <slug>] --check   exit 1 when a page differs

import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

type Generated = { page: string; generator: string; from: string; title: string; sidebarTitle?: string; description: string };
type Source = { name: string; lastSynced: string; generated?: Generated[] };
type Project = { slug: string; repo: string; checkout: string; sources: Source[] };

const root = join(dirname(new URL(import.meta.url).pathname), "..");
const registry = Bun.YAML.parse(readFileSync(join(root, "sync/registry.yaml"), "utf8")) as { projects: Project[] };
const args = process.argv.slice(2);
const check = args.includes("--check");
const only = args.includes("--project") ? args[args.indexOf("--project") + 1] : undefined;
if (args.includes("--project") && !registry.projects.some((p) => p.slug === only)) {
  console.error(`unknown project: ${only ?? "(missing)"}`);
  process.exit(1);
}
const GENERATED_MARK = "{/* Generated by scripts/gen.ts";

async function readSource(project: Project, sha: string, path: string): Promise<string> {
  const checkout = resolve(root, project.checkout);
  if (existsSync(checkout)) {
    const proc = Bun.spawnSync(["git", "-C", checkout, "show", `${sha}:${path}`], { stdout: "pipe", stderr: "pipe" });
    if (proc.exitCode === 0) return proc.stdout.toString();
  }
  const headers: Record<string, string> = { Accept: "application/vnd.github.raw", "User-Agent": "websublime-docs" };
  if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  const res = await fetch(`https://api.github.com/repos/${project.repo}/contents/${path}?ref=${sha}`, { headers });
  if (!res.ok) throw new Error(`${project.slug}: cannot read ${path} at ${sha} (${res.status})`);
  return res.text();
}

// Tags each line as inside a fenced code block or not. A fence closes only with
// the same character and at least the same length, on a line of its own.
function fencedLines(markdown: string): { line: string; fenced: boolean }[] {
  let fence: string | null = null;
  return markdown.split("\n").map((line) => {
    const marker = /^ {0,3}(`{3,}|~{3,})/.exec(line)?.[1];
    if (fence) {
      if (marker && marker[0] === fence[0] && marker.length >= fence.length && line.trim() === marker) fence = null;
      return { line, fenced: true };
    }
    if (marker) {
      fence = marker;
      return { line, fenced: true };
    }
    return { line, fenced: false };
  });
}

// Plain Markdown → MDX. Fenced blocks are copied as they are. In prose, inline
// code spans (which may wrap across lines) are copied as they are; HTML comments
// (maintainer notes) are dropped; `{` `}` are escaped; autolinks become links;
// every other `<` becomes `&lt;`. Existing backslash escapes are kept.
function toMdx(markdown: string): string {
  const out: string[] = [];
  let prose: string[] = [];
  for (const { line, fenced } of fencedLines(markdown)) {
    if (!fenced) {
      prose.push(line);
      continue;
    }
    if (prose.length) out.push(escapeProse(prose.join("\n")));
    prose = [];
    out.push(line);
  }
  if (prose.length) out.push(escapeProse(prose.join("\n")));
  return out.join("\n");
}

function escapeProse(text: string): string {
  const source = text.replace(/<!--[\s\S]*?-->\n?/g, "");
  let result = "";
  for (let i = 0; i < source.length; ) {
    const c = source[i];
    if (c === "`") {
      const run = /^`+/.exec(source.slice(i))![0];
      let close = -1;
      for (let j = source.indexOf(run, i + run.length); j >= 0; j = source.indexOf(run, j + 1)) {
        if (source.slice(i, j).includes("\n\n")) break;
        if (source[j - 1] !== "`" && source[j + run.length] !== "`") {
          close = j;
          break;
        }
      }
      const end = close >= 0 ? close + run.length : i + run.length;
      result += source.slice(i, end);
      i = end;
    } else if (c === "\\" && i + 1 < source.length) {
      result += source.slice(i, i + 2);
      i += 2;
    } else if (c === "{" || c === "}") {
      result += `\\${c}`;
      i++;
    } else if (c === "<") {
      const autolink = /^<(https?:\/\/[^\s>]+)>/.exec(source.slice(i));
      result += autolink ? `[${autolink[1]}](${autolink[1]})` : "&lt;";
      i += autolink ? autolink[0].length : 1;
    } else {
      result += c;
      i++;
    }
  }
  return result;
}

function frontmatter(entry: Generated, project: Project, from: string, sha: string): string {
  const lines = ["---", `title: ${JSON.stringify(entry.title)}`];
  if (entry.sidebarTitle) lines.push(`sidebarTitle: ${JSON.stringify(entry.sidebarTitle)}`);
  lines.push(`description: ${JSON.stringify(entry.description)}`, "---", "");
  lines.push(`${GENERATED_MARK} (${entry.generator}) from ${project.repo}:${from} at ${sha.slice(0, 12)}. Do not edit by hand; regenerate with scripts/gen.ts. */}`, "", "");
  return lines.join("\n");
}

const generators: Record<string, (text: string) => string> = {
  // A Markdown document; its first H1 is dropped (the page title replaces it).
  markdown: (text) => toMdx(text.replace(/^# .*\n+/m, "")),
  // Keep a Changelog: one <Update> per released version. [Unreleased] and the
  // preamble are left out (D5), and so are the version link definitions; other
  // reference definitions stay so that links inside entries keep working.
  // Headings inside code fences are neither split on nor demoted.
  "keep-a-changelog": (text) => {
    const body = text.replace(/^\[(?:unreleased|v?\d+\.\d+\.\d+[^\]]*)\]:\s+\S+.*$/gim, "");
    const sections: string[][] = [];
    for (const { line, fenced } of fencedLines(body)) {
      if (!fenced && line.startsWith("## ")) sections.push([line.slice(3)]);
      else sections.at(-1)?.push(!fenced && line.startsWith("### ") ? line.slice(1) : line);
    }
    return sections
      .map(([heading, ...rest]) => {
        const m = /^\[?([^\]\s(]+)\]?(?:\([^)]*\))?\s*(?:[-–—]\s*(\d{4}-\d{2}-\d{2}))?\s*(\[YANKED\])?/i.exec(heading);
        if (!m || /unreleased/i.test(m[1])) return "";
        const description = [m[2], m[3] ? "yanked" : ""].filter(Boolean).join(" · ");
        const content = toMdx(rest.join("\n").trim());
        return `<Update label="${m[1]}"${description ? ` description="${description}"` : ""}>\n\n${content}\n\n</Update>\n`;
      })
      .filter(Boolean)
      .join("\n");
  },
};

let stale = 0;
const declared = new Set<string>();
for (const project of registry.projects.filter((p) => !only || p.slug === only)) {
  for (const source of project.sources) {
    for (const entry of source.generated ?? []) {
      declared.add(`${entry.page}.mdx`);
      const generate = generators[entry.generator];
      if (!generate) throw new Error(`${project.slug}/${source.name}: unknown generator ${entry.generator}`);
      const text = await readSource(project, source.lastSynced, entry.from);
      const output = `${frontmatter(entry, project, entry.from, source.lastSynced)}${generate(text).trim()}\n`;
      const path = join(root, `${entry.page}.mdx`);
      const current = existsSync(path) ? readFileSync(path, "utf8") : null;
      if (current === output) continue;
      if (check) {
        console.error(`out of date: ${entry.page}.mdx (run: bun scripts/gen.ts --project ${project.slug})`);
        stale++;
      } else {
        mkdirSync(dirname(path), { recursive: true });
        writeFileSync(path, output);
        console.log(`wrote ${entry.page}.mdx`);
      }
    }
  }
}
// A generated page whose registry entry is gone is stale too (full runs only).
if (!only) {
  for (const rel of new Bun.Glob("**/*.mdx").scanSync({ cwd: root })) {
    if (!declared.has(rel) && readFileSync(join(root, rel), "utf8").includes(GENERATED_MARK)) {
      console.error(`orphan generated page: ${rel} (no registry entry; remove it or declare it)`);
      stale++;
    }
  }
}
if (stale) process.exit(1);
if (check) console.log("generated pages are up to date");
