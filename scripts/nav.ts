#!/usr/bin/env bun
// Project navigation for full-width overview pages (D25). Custom-mode pages have
// no Mintlify sidebar, so each project's navigation is generated from docs.json
// into snippets/nav/<slug>.mdx, which the project's overview page imports.
// Labels come from each page's `sidebarTitle` (or `title`) frontmatter. Mintlify drops
// <nav>, <main>, <article> and <footer> elements from MDX, so the markup uses
// <div role="navigation">.
//
//   bun scripts/nav.ts          write the snippets
//   bun scripts/nav.ts --check  exit 1 when a snippet differs (CI)

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

type Group = { group: string; pages: string[] };
type Product = { product: string; groups?: Group[] };

const root = join(dirname(new URL(import.meta.url).pathname), "..");
const check = process.argv.includes("--check");
const docs = JSON.parse(readFileSync(join(root, "docs.json"), "utf8")) as { navigation: { products: Product[] } };

function label(page: string): string {
  const text = readFileSync(join(root, `${page}.mdx`), "utf8");
  const fm = /^---\n([\s\S]*?)\n---/.exec(text)?.[1] ?? "";
  const field = (key: string) => new RegExp(`^${key}:\\s*"?(.*?)"?\\s*$`, "m").exec(fm)?.[1];
  const value = field("sidebarTitle") ?? field("title");
  if (!value) throw new Error(`${page}.mdx has no sidebarTitle or title`);
  return value;
}

const escape = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/[{}]/g, (c) => `\\${c}`);
const expected = new Map<string, string>();
for (const product of docs.navigation.products) {
  const pages = (product.groups ?? []).flatMap((g) => g.pages);
  const overview = pages.find((p) => p.endsWith("/overview"));
  if (!overview) continue; // the Hub has no project navigation
  const slug = overview.split("/")[0];
  const lines = [
    "{/* Generated by scripts/nav.ts from docs.json. Do not edit by hand. */}",
    "",
    `<div className="ws-docnav" role="navigation" aria-label="${escape(product.product)} docs">`,
  ];
  for (const group of product.groups ?? []) {
    lines.push(`  <p className="ws-label">${escape(group.group)}</p>`);
    for (const page of group.pages) {
      const current = page === overview ? ' aria-current="page"' : "";
      lines.push(`  <a href="/${page}"${current}>${escape(label(page))}</a>`);
    }
  }
  lines.push("</div>", "");
  expected.set(`snippets/nav/${slug}.mdx`, lines.join("\n"));
}

let stale = 0;
for (const [rel, content] of expected) {
  const path = join(root, rel);
  if (existsSync(path) && readFileSync(path, "utf8") === content) continue;
  if (check) {
    console.error(`out of date: ${rel} (run: bun scripts/nav.ts)`);
    stale++;
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${rel}`);
  }
}
const navDir = join(root, "snippets/nav");
for (const file of existsSync(navDir) ? readdirSync(navDir) : []) {
  if (!expected.has(`snippets/nav/${file}`)) {
    console.error(`orphan navigation snippet: snippets/nav/${file} (no product in docs.json)`);
    stale++;
  }
}
if (stale) process.exit(1);
if (check) console.log("project navigation is up to date");
